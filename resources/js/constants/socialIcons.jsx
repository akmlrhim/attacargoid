/**
 * Resolve the icon + label for a stored social link, falling back to a
 * generic link icon (and its custom label) for anything not in the map.
 *
 * @param {{ platform: string, label?: string|null, url: string }} link
 */
export function resolveSocialLink(link) {
  const preset = SOCIAL_PLATFORMS[link.platform];

  return {
    label: preset?.label ?? link.label ?? "Link",
    Icon: preset?.icon ?? LinkIcon,
    href: link.url,
  };
}
